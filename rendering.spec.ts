test('real video seeks, reverse, freeze and frame-accurate audio/video export', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  const result = await page.evaluate(async () => {
    const { buildInitialWorkspace } = await import('/src/utils/initialProject.ts');
    const { exportProjectToVideoFile } = await import('/src/utils/compositor.ts');
    const { parseUploadedMediaFile, createClipFromAsset } = await import('/src/utils/mediaHelpers.ts');
    const { createRemapPreset } = await import('/src/utils/timeRemap.ts');
    const { PreviewFrameCache, renderPreviewRange, seekVideoFrame } = await import('/src/utils/previewCache.ts');
    const workspace = buildInitialWorkspace();
    const image = { ...workspace.project.clips[0], duration: 2, transitionIn: 'none', transitionOut: 'none', filters: { brightness: 100, contrast: 100, saturation: 100, hue: 0, blur: 0, vignette: 0, temperature: 0, presetName: 'Original' } };
    const music = { ...workspace.project.clips.find((clip) => clip.type === 'audio')!, duration: 2, fadeIn: 0, fadeOut: 0 };
    const fixtureProject = { ...workspace.project, clips: [image, music], markers: [] };
    const signal = new AbortController().signal;
    let progress = 0;
    const output = await exportProjectToVideoFile(fixtureProject, workspace.assets, '720p', (value) => { progress = value; }, signal);
    const asset = await parseUploadedMediaFile(new File([output.blob], 'render-test.webm', { type: output.mimeType }));
    if (!asset) throw new Error('Unable to reimport rendered video');
    const audioContext = new AudioContext();
    const sound = await audioContext.decodeAudioData(await output.blob.arrayBuffer());
    const audioEnergy = sound.getChannelData(0).reduce((sum, sample) => sum + sample * sample, 0);
    await audioContext.close();
    const clip = { ...createClipFromAsset(asset, 'track-v1', 0), duration: 2, transitionIn: 'none', transitionOut: 'none', muted: true };
    const project = { ...fixtureProject, clips: [clip] };
    const assets = new Map([[asset.id, asset]]);
    const digestFrame = async (cache: InstanceType<typeof PreviewFrameCache>, time: number) => {
      const stored = cache.frames.get(cache.frameIndex(time))!;
      const hash = await crypto.subtle.digest('SHA-256', await stored.blob.arrayBuffer());
      return [...new Uint8Array(hash)].map((value) => value.toString(16).padStart(2, '0')).join('');
    };
    const forward = new PreviewFrameCache(30, 320, 180);
    await renderPreviewRange(project, assets, forward, { start: 1.5, end: 1.5 + 1 / 30 }, signal, () => {});
    const reverse = new PreviewFrameCache(30, 320, 180);
    const reverseClip = { ...clip, timeRemap: createRemapPreset(clip, 'reverse', 0) };
    await renderPreviewRange({ ...project, clips: [reverseClip] }, assets, reverse, { start: 0.5, end: 0.5 + 1 / 30 }, signal, () => {});
    const forwardHash = await digestFrame(forward, 1.5);
    const reverseHash = await digestFrame(reverse, 0.5);

    const freeze = new PreviewFrameCache(30, 320, 180);
    const frozenClip = { ...clip, timeRemap: createRemapPreset(clip, 'freeze', 0.75) };
    await renderPreviewRange({ ...project, clips: [frozenClip] }, assets, freeze, { start: 0.5, end: 0.5 + 1 / 30 }, signal, () => {});
    await renderPreviewRange({ ...project, clips: [frozenClip] }, assets, freeze, { start: 1.5, end: 1.5 + 1 / 30 }, signal, () => {});
    const freezeA = await digestFrame(freeze, 0.5);
    const freezeB = await digestFrame(freeze, 1.5);

    const remappedOutput = await exportProjectToVideoFile({ ...project, clips: [reverseClip] }, [asset], '720p', () => {}, signal);
    const video = document.createElement('video');
    const sourceVideo = document.createElement('video');
    const exportUrl = URL.createObjectURL(remappedOutput.blob);
    video.src = exportUrl;
    sourceVideo.src = asset.url;
    video.preload = sourceVideo.preload = 'auto';
    video.muted = sourceVideo.muted = true;
    await seekVideoFrame(video, 0.5, signal);
    await seekVideoFrame(sourceVideo, 1.5, signal);
    const canvas = document.createElement('canvas');
    canvas.width = 128;
    canvas.height = 72;
    const context = canvas.getContext('2d')!;
    context.drawImage(sourceVideo, 0, 0, 128, 72);
    const reference = context.getImageData(0, 0, 128, 72).data;
    context.drawImage(video, 0, 0, 128, 72);
    const actual = context.getImageData(0, 0, 128, 72).data;
    let difference = 0;
    for (let i = 0; i < reference.length; i++) difference += Math.abs(reference[i] - actual[i]);
    const duration = video.duration;
    const dimensions = [video.videoWidth, video.videoHeight];
    video.removeAttribute('src'); video.load();
    sourceVideo.removeAttribute('src'); sourceVideo.load();
    URL.revokeObjectURL(exportUrl);
    for (const cache of [forward, reverse, freeze]) cache.clear();
    return { progress, bytes: output.blob.size, duration, dimensions, audioEnergy, forwardHash, reverseHash, freezeA, freezeB, difference: difference / reference.length };
  });
  expect(result.progress).toBe(100);
  expect(result.bytes).toBeGreaterThan(10000);
  expect(result.audioEnergy).toBeGreaterThan(10);
  expect(result.duration).toBeCloseTo(2, 1);
  expect(result.dimensions).toEqual([1280, 720]);
  expect(result.forwardHash).toBe(result.reverseHash);
  expect(result.freezeA).toBe(result.freezeB);
  expect(result.difference).toBeLessThan(4);
  expect(errors).toEqual([]);
});

