test('imported video can be remapped, previewed, saved and exported through the interface', async ({ page }) => {
  const errors: string[] = [];
  page.on('pageerror', (error) => errors.push(error.message));
  await page.goto('/');
  await useManualPreview(page);
  const bytes = await page.evaluate(async () => {
    const { buildInitialWorkspace } = await import('/src/utils/initialProject.ts');
    const { exportProjectToVideoFile } = await import('/src/utils/compositor.ts');
    const workspace = buildInitialWorkspace();
    const clip = { ...workspace.project.clips[0], duration: 1, transitionIn: 'none', transitionOut: 'none' };
    const result = await exportProjectToVideoFile({ ...workspace.project, clips: [clip] }, workspace.assets, '720p', () => {}, new AbortController().signal);
    return Array.from(new Uint8Array(await result.blob.arrayBuffer()));
  });
  await page.getByRole('button', { name: 'OTTO', exact: true }).click();
  await page.getByRole('button', { name: 'Novo Projeto em Branco', exact: true }).click();
  await page.locator('input[type="file"][accept^="video/*,image/*,audio/*"]').setInputFiles({ name: 'video-de-teste.webm', mimeType: 'video/webm', buffer: Buffer.from(bytes) });
  const media = page.locator('[draggable="true"]').filter({ has: page.getByText('video-de-teste.webm', { exact: true }) });
  await expect(media).toBeVisible();
  await media.getByTitle('Adicionar à linha do tempo').click();
  await page.getByRole('button', { name: 'Time Remapping', exact: true }).click();
  await page.getByRole('button', { name: 'Reverso', exact: true }).click();
  await expect(page.locator('.remap-readout small')).toContainText('-1.00x');
  await page.keyboard.press('ArrowRight');
  await page.getByRole('button', { name: /Renderizar previa/ }).click();
  await expect(page.getByRole('status')).toContainText('30 quadros');

  await page.getByRole('button', { name: 'OTTO', exact: true }).click();
  const projectDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Salvar Projeto (.json)', exact: true }).click();
  const projectFile = await (await projectDownload).path();
  if (!projectFile) throw new Error('Project download missing');
  const saved = JSON.parse(await readFile(projectFile, 'utf8'));
  expect(saved.clips[0].timeRemap.enabled).toBe(true);
  expect(saved.clips[0].timeRemap.keyframes).toHaveLength(2);
  expect(saved.clips[0].timeRemap.keyframes[0].sourceTime).toBeGreaterThan(saved.clips[0].timeRemap.keyframes[1].sourceTime);

  await page.getByRole('button', { name: 'Exportar', exact: true }).click();
  await page.getByRole('button', { name: /HD 720p Rapido|HD 720p Rápido/ }).click();
  const videoDownload = page.waitForEvent('download');
  await page.getByRole('button', { name: /Renderizar e Baixar V/ }).click();
  const downloaded = await videoDownload;
  const path = await downloaded.path();
  if (!path) throw new Error('Video download missing');
  expect((await stat(path)).size).toBeGreaterThan(10000);
  expect(downloaded.suggestedFilename()).toMatch(/720p\.webm$/);
  await expect(page.getByText('Seu vídeo está pronto!', { exact: true })).toBeVisible();
  expect(errors).toEqual([]);
});

test('screen-recording WebM duration is detected rather than guessed', async ({ page }) => {
  await page.goto('/');
  const result = await page.evaluate(async () => {
    const { parseUploadedMediaFile } = await import('/src/utils/mediaHelpers.ts');
    const canvas = document.createElement('canvas');
    canvas.width = 160;
    canvas.height = 90;
    const context = canvas.getContext('2d')!;
    const stream = canvas.captureStream(15);
    const recorder = new MediaRecorder(stream, { mimeType: 'video/webm;codecs=vp8' });
    const chunks: Blob[] = [];
    const recording = new Promise<Blob>((resolve) => {
      recorder.ondataavailable = (event) => chunks.push(event.data);
      recorder.onstop = () => resolve(new Blob(chunks, { type: 'video/webm' }));
    });
    recorder.start(100);
    const timer = setInterval(() => { context.fillStyle = `hsl(${performance.now() % 360}, 70%, 50%)`; context.fillRect(0, 0, 160, 90); }, 50);
    await new Promise((resolve) => setTimeout(resolve, 850));
    recorder.stop();
    clearInterval(timer);
    const blob = await recording;
    stream.getTracks().forEach((track) => track.stop());
    const asset = await parseUploadedMediaFile(new File([blob], 'gravacao.webm', { type: 'video/webm' }));
    return { duration: asset?.duration, thumbnail: !!asset?.thumbnail };
  });
  expect(result.thumbnail).toBe(true);
  expect(result.duration).toBeGreaterThan(0.4);
  expect(result.duration).toBeLessThan(1.5);
});